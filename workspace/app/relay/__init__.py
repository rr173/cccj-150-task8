"""回执中继包：交换包交付回执中继（Delivery Receipt Relay）。

独立子系统（独立 SQLite 库、独立密钥目录），快照接收服务把审计事件
（创建 / 分块接受或拒绝 / 移交 / 终检……）按**会话修订号**推送到中继；
中继为每个发送方维护连续水位，允许乱序、重复与批量重放，仅在
「前序齐全 + 事件哈希链 + 签章 + 会话版本跃迁合法」时推进水位；
发现缺口 / 同序号异内容 / 分叉链 / 非法状态跃迁时**隔离该会话**并
返回可定位差异，不影响其他会话。中继按接收机构签发**可离线核验**的
Ed25519 回执包。

模块划分：

* :mod:`app.relay.config`   —— 路径 / 过期 / 租约等配置
* :mod:`app.relay.crypto`   —— 规范化哈希、机构密钥库、回执签章
* :mod:`app.relay.store`    —— SQLite schema / 事务 / 领取租约
* :mod:`app.relay.service`  —— 事件接收、水位推进、隔离、回执导出/清理授权
* :mod:`app.relay.verifier` —— 独立离线核验（仅凭回执包与机构公钥）
"""
